-- Apaga e recria todas as tabelas do Sentry, no estado final das migrações V1 a V4. APAGA TODOS OS DADOS: só para
-- ambiente local. Mantenha em sincronia ao criar novas migrações.
--
-- A flyway_schema_history fica de fora de propósito: sem ela, o Flyway recusa subir com o schema já preenchido. Se ela
-- não existir (banco que nunca passou pelo Flyway), não rode este script: basta subir a aplicação.

BEGIN;

DROP TABLE IF EXISTS
    spring_session_attributes,
    spring_session,
    oauth2_rotated_refresh_tokens,
    oauth2_authorization_consent,
    oauth2_authorization,
    system_redirect_uris,
    role_users,
    role_actions,
    roles,
    actions,
    access_logs,
    systems,
    password_tokens,
    users,
    organizations,
    mfa_tokens;

CREATE TABLE mfa_tokens (
    id_mfa_token BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(255) NOT NULL,
    token        VARCHAR(255) NOT NULL UNIQUE,
    username     VARCHAR(255) NOT NULL,
    is_used      BOOLEAN      NOT NULL,
    valid_until  TIMESTAMP,
    created_at   TIMESTAMP,
    used_at      TIMESTAMP
);

CREATE TABLE organizations (
    id_organization BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    external_code   VARCHAR(255) UNIQUE,
    uuid            UUID         NOT NULL UNIQUE,
    is_active       BOOLEAN      NOT NULL,
    is_deleted      BOOLEAN      NOT NULL,
    created_by      VARCHAR(255),
    created_at      TIMESTAMP,
    updated_by      VARCHAR(255),
    updated_at      TIMESTAMP
);

CREATE TABLE users (
    id_user             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                UUID         NOT NULL UNIQUE,
    name                VARCHAR(255) NOT NULL,
    authentication_type VARCHAR(255),
    username            VARCHAR(255) NOT NULL UNIQUE,
    password            VARCHAR(255),
    email               VARCHAR(255) NOT NULL UNIQUE,
    is_active           BOOLEAN      NOT NULL,
    is_deleted          BOOLEAN      NOT NULL,
    created_by          VARCHAR(255),
    created_at          TIMESTAMP,
    updated_by          VARCHAR(255),
    updated_at          TIMESTAMP
);

-- RN-F1-02.1: o login não diferencia maiúsculas; o banco garante que não existam dois usernames iguais assim
CREATE UNIQUE INDEX users_username_lower_key ON users (lower(username));

CREATE TABLE password_tokens (
    id_password_token BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token             VARCHAR(255) NOT NULL UNIQUE,
    is_used           BOOLEAN      NOT NULL,
    id_user           BIGINT       NOT NULL REFERENCES users (id_user),
    valid_until       TIMESTAMP,
    created_by        VARCHAR(255),
    created_at        TIMESTAMP,
    updated_by        VARCHAR(255),
    updated_at        TIMESTAMP
);

-- F1-01: sistema externo como cliente OAuth; client_id = external_code, obrigatório
CREATE TABLE systems (
    id_system          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_organization    BIGINT       NOT NULL REFERENCES organizations (id_organization),
    external_code      VARCHAR(255) NOT NULL UNIQUE,
    description        VARCHAR(255),
    url                VARCHAR(255),
    scopes             VARCHAR(255),
    uuid               UUID         NOT NULL UNIQUE,
    is_active          BOOLEAN      NOT NULL,
    is_deleted         BOOLEAN      NOT NULL,
    created_by         VARCHAR(255),
    created_at         TIMESTAMP,
    updated_by         VARCHAR(255),
    updated_at         TIMESTAMP,
    client_type        VARCHAR(20)  NOT NULL DEFAULT 'CONFIDENTIAL'
        CHECK (client_type IN ('PUBLIC', 'CONFIDENTIAL')),
    client_secret_hash VARCHAR(255),
    is_trusted         BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE system_redirect_uris (
    id_system BIGINT        NOT NULL REFERENCES systems (id_system) ON DELETE CASCADE,
    uri       VARCHAR(2048) NOT NULL,
    uri_type  VARCHAR(20)   NOT NULL CHECK (uri_type IN ('LOGIN', 'LOGOUT')),
    PRIMARY KEY (id_system, uri_type, uri)
);

-- F1-10: tentativas com usuário inexistente, canal e User-Agent
CREATE TABLE access_logs (
    id_access_log      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user            BIGINT REFERENCES users (id_user),
    attempted_at       TIMESTAMP,
    attempt_result     VARCHAR(255),
    ip_host            VARCHAR(255),
    id_system          BIGINT REFERENCES systems (id_system),
    attempted_username VARCHAR(255),
    channel            VARCHAR(20) CHECK (channel IN ('PKCE', 'DIRECT')),
    user_agent         VARCHAR(512)
);

CREATE TABLE actions (
    cd_action   VARCHAR(255) PRIMARY KEY,
    action_type VARCHAR(255),
    id_system   BIGINT  NOT NULL REFERENCES systems (id_system),
    is_active   BOOLEAN NOT NULL,
    is_deleted  BOOLEAN NOT NULL,
    created_by  VARCHAR(255),
    created_at  TIMESTAMP,
    updated_by  VARCHAR(255),
    updated_at  TIMESTAMP
);

CREATE TABLE roles (
    id_role         BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_system       BIGINT  NOT NULL REFERENCES systems (id_system),
    id_organization BIGINT  NOT NULL REFERENCES organizations (id_organization),
    system_role     VARCHAR(255),
    external_role   VARCHAR(255),
    role_type       VARCHAR(255),
    uuid            UUID    NOT NULL UNIQUE,
    is_active       BOOLEAN NOT NULL,
    is_deleted      BOOLEAN NOT NULL,
    created_by      VARCHAR(255),
    created_at      TIMESTAMP,
    updated_by      VARCHAR(255),
    updated_at      TIMESTAMP
);

CREATE TABLE role_actions (
    id_role_action BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_role        BIGINT  NOT NULL REFERENCES roles (id_role),
    cd_action      VARCHAR(255) NOT NULL REFERENCES actions (cd_action),
    is_active      BOOLEAN NOT NULL,
    is_deleted     BOOLEAN NOT NULL,
    created_by     VARCHAR(255),
    created_at     TIMESTAMP,
    updated_by     VARCHAR(255),
    updated_at     TIMESTAMP
);

CREATE TABLE role_users (
    id_role_user BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_role      BIGINT  NOT NULL REFERENCES roles (id_role),
    id_user      BIGINT  NOT NULL REFERENCES users (id_user),
    is_active    BOOLEAN NOT NULL,
    is_deleted   BOOLEAN NOT NULL,
    created_by   VARCHAR(255),
    created_at   TIMESTAMP,
    updated_by   VARCHAR(255),
    updated_at   TIMESTAMP
);

-- F1-03: esquemas do Spring Authorization Server 7.1, adaptados ao PostgreSQL como o próprio
-- arquivo oficial orienta (blob -> text, timestamp -> timestamptz)
CREATE TABLE oauth2_authorization (
    id                            VARCHAR(100)  NOT NULL,
    registered_client_id          VARCHAR(100)  NOT NULL,
    principal_name                VARCHAR(200)  NOT NULL,
    authorization_grant_type      VARCHAR(100)  NOT NULL,
    authorized_scopes             VARCHAR(1000) DEFAULT NULL,
    attributes                    TEXT          DEFAULT NULL,
    state                         VARCHAR(500)  DEFAULT NULL,
    authorization_code_value      TEXT          DEFAULT NULL,
    authorization_code_issued_at  TIMESTAMPTZ   DEFAULT NULL,
    authorization_code_expires_at TIMESTAMPTZ   DEFAULT NULL,
    authorization_code_metadata   TEXT          DEFAULT NULL,
    access_token_value            TEXT          DEFAULT NULL,
    access_token_issued_at        TIMESTAMPTZ   DEFAULT NULL,
    access_token_expires_at       TIMESTAMPTZ   DEFAULT NULL,
    access_token_metadata         TEXT          DEFAULT NULL,
    access_token_type             VARCHAR(100)  DEFAULT NULL,
    access_token_scopes           VARCHAR(1000) DEFAULT NULL,
    oidc_id_token_value           TEXT          DEFAULT NULL,
    oidc_id_token_issued_at       TIMESTAMPTZ   DEFAULT NULL,
    oidc_id_token_expires_at      TIMESTAMPTZ   DEFAULT NULL,
    oidc_id_token_metadata        TEXT          DEFAULT NULL,
    refresh_token_value           TEXT          DEFAULT NULL,
    refresh_token_issued_at       TIMESTAMPTZ   DEFAULT NULL,
    refresh_token_expires_at      TIMESTAMPTZ   DEFAULT NULL,
    refresh_token_metadata        TEXT          DEFAULT NULL,
    user_code_value               TEXT          DEFAULT NULL,
    user_code_issued_at           TIMESTAMPTZ   DEFAULT NULL,
    user_code_expires_at          TIMESTAMPTZ   DEFAULT NULL,
    user_code_metadata            TEXT          DEFAULT NULL,
    device_code_value             TEXT          DEFAULT NULL,
    device_code_issued_at         TIMESTAMPTZ   DEFAULT NULL,
    device_code_expires_at        TIMESTAMPTZ   DEFAULT NULL,
    device_code_metadata          TEXT          DEFAULT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE oauth2_authorization_consent (
    registered_client_id VARCHAR(100)  NOT NULL,
    principal_name       VARCHAR(200)  NOT NULL,
    authorities          VARCHAR(1000) NOT NULL,
    PRIMARY KEY (registered_client_id, principal_name)
);

-- RN-F1-06.4: hashes dos refresh tokens já rotacionados; reapresentar um deles revoga a autorização inteira
CREATE TABLE oauth2_rotated_refresh_tokens (
    token_hash       VARCHAR(100) PRIMARY KEY,
    authorization_id VARCHAR(100) NOT NULL REFERENCES oauth2_authorization (id) ON DELETE CASCADE,
    rotated_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- F1-09: sessão SSO, esquema oficial do Spring Session JDBC 4.1 para PostgreSQL
CREATE TABLE spring_session (
    primary_id            CHAR(36)     NOT NULL,
    session_id            CHAR(36)     NOT NULL,
    creation_time         BIGINT       NOT NULL,
    last_access_time      BIGINT       NOT NULL,
    max_inactive_interval INT          NOT NULL,
    expiry_time           BIGINT       NOT NULL,
    principal_name        VARCHAR(100),
    CONSTRAINT spring_session_pk PRIMARY KEY (primary_id)
);

CREATE UNIQUE INDEX spring_session_ix1 ON spring_session (session_id);
CREATE INDEX spring_session_ix2 ON spring_session (expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session (principal_name);

CREATE TABLE spring_session_attributes (
    session_primary_id CHAR(36)     NOT NULL,
    attribute_name     VARCHAR(200) NOT NULL,
    attribute_bytes    BYTEA        NOT NULL,
    CONSTRAINT spring_session_attributes_pk PRIMARY KEY (session_primary_id, attribute_name),
    CONSTRAINT spring_session_attributes_fk FOREIGN KEY (session_primary_id)
        REFERENCES spring_session (primary_id) ON DELETE CASCADE
);

COMMIT;
